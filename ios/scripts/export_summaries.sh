#!/bin/sh
# Writes testsuallari/summaries_data.js (const summariesData) from the iOS SubjectSummaries Swift files,
# so the website's "Xülasə" tab shows exactly what the app shows.
set -e
root="$(cd "$(dirname "$0")/../.." && pwd)"
tmp="$(mktemp -d)"
cp "$root/ios/scripts/export_summaries_main.swift" "$tmp/main.swift"   # top-level code must live in main.swift
xcrun swiftc -O -o "$tmp/dump" "$root"/ios/Imtahan/Store/SubjectSummaries*.swift "$tmp/main.swift"
{
  echo "// Generated by ios/scripts/export_summaries.sh from ios/Imtahan/Store/SubjectSummaries*.swift. Do not edit by hand."
  printf "const summariesData = "
  "$tmp/dump"
  echo ";"
} > "$root/testsuallari/summaries_data.js"
rm -rf "$tmp"
echo "summaries_data.js written"
